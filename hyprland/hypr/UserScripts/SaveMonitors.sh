#!/usr/bin/env bash
# Dump the live monitor layout (e.g. set with wdisplays) to monitors.lua so it survives reloads.
out="$HOME/.config/hypr/monitors.lua"
json=$(hyprctl monitors -j) || exit 1
[ "$(jq length <<<"$json")" -gt 0 ] || exit 1  # never wipe the file with an empty layout

{
  echo "-- Generated by SaveMonitors.sh on $(date '+%F %T'). Re-run after changing the layout in wdisplays."
  jq -r '.[] | select(.disabled | not) |
    "\nhl.monitor({\n    output = \"\(.name)\",\n    mode = \"\(.width)x\(.height)@\(.refreshRate * 100 | round / 100)\",\n    position = \"\(.x)x\(.y)\",\n    scale = \(.scale),\n    transform = \(.transform),\n    vrr = \(if .vrr then 1 else 0 end)\n})"' <<<"$json"
} >"$out.tmp" && mv "$out.tmp" "$out"

notify-send -a Écrans "Disposition enregistrée" "$(jq -r '.[] | "\(.name) \(.x)x\(.y) ×\(.scale)"' <<<"$json")" 2>/dev/null
